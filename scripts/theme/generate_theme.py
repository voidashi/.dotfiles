#!/usr/bin/env python3
"""Voidashi theme generator.

Reads palette.json (the single source of truth, transcribed from
docs/design/RICE-GUIDE.md and docs/design/DESIGN-SYSTEM.md) and writes the
color-only config partials each app natively includes. See RICE-GUIDE.md,
"Working rules".

The emitters here take two arguments: the palette, and the semantic layer that
roles.py builds from it. A colour decision belongs there and a toolkit's key
names belong here, which is the split that lets one decision reach GTK, Qt and
the terminals without being written three times.

Never hand-edit the files this script writes; they carry a GENERATED
header. Edit palette.json and rerun this script instead.
"""

import json
import re
from pathlib import Path

import roles

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent.parent
CONFIG = REPO_ROOT / ".config"

SOURCE_NOTE = "docs/design/RICE-GUIDE.md"

HEX_COLOUR = re.compile(r"#[0-9a-fA-F]{6}\Z")


# =====================================================================
#  Source and writing
# =====================================================================

def colour_keys(p: dict):
    """Every place in palette.json that must hold a colour, as (name, value).

    Written out rather than inferred, because the file also holds glyphs,
    geometry numbers and font names, and a walk that guessed which is which
    would have to guess again every time a key is added.

    Roles are not in here and cannot be. They live in roles.py and hold a
    colour this file already holds, which roles.validate() is what enforces.
    """
    for family, shades in p["scales"].items():
        for step, value in shades.items():
            yield f"scales.{family}.{step}", value
    for name, entry in p["alert"].items():
        for key in ("fg", "bg", "border"):
            yield f"alert.{name}.{key}", entry[key]
    for i, value in enumerate(p["ansi16"]):
        yield f"ansi16[{i}]", value


def validate_palette(p: dict) -> None:
    """Refuse a colour that is not #RRGGBB, here rather than downstream.

    Dropping the '#' from one value is a single keystroke and used to survive
    every check this repository has. check_sync compares the output against
    this generator, so a malformed input is "in sync" by construction, and
    check_drift's pattern needs the '#' to see the value at all. What shipped
    was a stylesheet GTK rejected with two parse errors, while both checks
    reported clean and the checker's palette count silently grew by one.
    """
    bad = [f"{name} = {value!r}" for name, value in colour_keys(p)
           if not isinstance(value, str) or not HEX_COLOUR.match(value)]
    if bad:
        raise SystemExit(
            "palette.json: these must be #RRGGBB and are not:\n  " + "\n  ".join(bad)
        )


def load_palette() -> dict:
    with open(SCRIPT_DIR / "palette.json", encoding="utf-8") as f:
        p = json.load(f)
    validate_palette(p)
    # Here rather than at each emitter, so that a broken semantic layer stops
    # the run instead of reaching one file and not another. check_palette.py
    # loads through this function too and inherits the check for free.
    roles.validate(p, roles.build(p))
    return p


def header(comment_start: str, comment_end: str = "") -> str:
    lines = [
        "GENERATED by scripts/theme/generate_theme.py from scripts/theme/palette.json",
        "Do not hand-edit: edit palette.json and rerun the generator.",
        f"Voidashi color scheme. See {SOURCE_NOTE}",
    ]
    return "\n".join(f"{comment_start} {line}{comment_end}" for line in lines) + "\n\n"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  wrote {path.relative_to(REPO_ROOT)}")


