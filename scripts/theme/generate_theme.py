def kde_font(p: dict, size_key: str = "ui_size", mono: bool = False) -> str:
    """One font in the ten-field form KDE writes into kdeglobals.

    The fields are family, point size, pixel size, style hint, weight, italic,
    underline, strikeout, fixed pitch, raw mode. Only the first, second and
    fifth carry a decision; the rest are the defaults KDE itself writes.

    The weight is the Qt 0-99 scale, not the CSS one. Passing 500 there, which
    is what geometry.font_weight_ui holds, does not fail: it clamps and renders
    as Black. 57 is the Medium that 500 means.
    """
    t = p["typography"]
    family = t["mono_family"] if mono else t["ui_family"]
    weight = t["kde_weight_mono"] if mono else t["kde_weight"]
    return f"{family},{t[size_key]},-1,5,{weight},0,0,0,0,0"


def gen_kde_colors(p: dict) -> str:
    """KDE colour scheme, for the Qt half of the desktop.

    Nine KDE applications are installed (dolphin, ark, gwenview, kate,
    spectacle, and so on) and they read their colours from kdeglobals rather
    than from anything GTK. The format is INI with one block per role and
    values as "R,G,B" rather than hex.

    The blocks are not interchangeable: Window is the chrome, View is the
    content area a list or a text buffer draws on, Button is a raised control,
    Tooltip floats above everything. Mapping them all to one colour is what
    makes a Qt application look flat and wrong.
    """
    s, a = p["scales"], p["alert"]
    rgb = lambda h: ",".join(str(int(h.lstrip("#")[i:i + 2], 16)) for i in (0, 2, 4))

    ice_focus = s["ice"]["400"]
    shared = {
        "DecorationFocus": ice_focus,
        "DecorationHover": ice_focus,
        "ForegroundActive": s["ice"]["300"],
        "ForegroundInactive": s["ink"]["4"],
        "ForegroundLink": s["ice"]["300"],
        "ForegroundVisited": s["ash"]["300"],
        "ForegroundNegative": a["critical"]["fg"],
        "ForegroundNeutral": a["caution"]["fg"],
        "ForegroundPositive": a["good"]["fg"],
    }

    # background normal, background alternate, foreground normal
    roles = {
        "Window": (s["void"]["10"], s["void"]["20"], s["ink"]["1"]),
        "View": (s["void"]["00"], s["void"]["10"], s["ink"]["1"]),
        "Button": (s["void"]["20"], s["void"]["30"], s["ink"]["1"]),
        "Selection": (s["ice"]["600"], s["ice"]["700"], s["ink"]["0"]),
        "Tooltip": (s["void"]["30"], s["void"]["40"], s["ink"]["1"]),
        "Complementary": (s["void"]["10"], s["void"]["20"], s["ink"]["1"]),
        "Header": (s["void"]["20"], s["void"]["30"], s["ink"]["1"]),
    }

    out = header("#")
    for role, (bg, alt, fg) in roles.items():
        out += f"[Colors:{role}]\n"
        out += f"BackgroundNormal={rgb(bg)}\n"
        out += f"BackgroundAlternate={rgb(alt)}\n"
        out += f"ForegroundNormal={rgb(fg)}\n"
        for key, hexval in shared.items():
            # Selection inverts: its foreground roles read against Ice, not void.
            if role == "Selection" and key == "ForegroundInactive":
                hexval = s["ink"]["2"]
            out += f"{key}={rgb(hexval)}\n"
        out += "\n"

    # Title bars. activeBlend/inactiveBlend are the gradient partner Breeze uses;
    # keeping them equal to the background is what removes the gradient.
    out += "[WM]\n"
    out += f"activeBackground={rgb(s['void']['20'])}\n"
    out += f"activeBlend={rgb(s['void']['20'])}\n"
    out += f"activeForeground={rgb(s['ink']['0'])}\n"
    out += f"inactiveBackground={rgb(s['void']['10'])}\n"
    out += f"inactiveBlend={rgb(s['void']['10'])}\n"
    out += f"inactiveForeground={rgb(s['ink']['3'])}\n"
    # The title bar font lives in [WM], and this whole section is replaced on
    # merge, so it has to be emitted here or it is dropped on the next run.
    out += f"activeFont={kde_font(p)}\n\n"

    # Disabled and inactive text. These control fading only, never hue; the
    # values are Breeze's, which are tuned and not worth reinventing.
    out += (
        "[ColorEffects:Disabled]\n"
        "Color=56,56,56\nColorAmount=0\nColorEffect=0\n"
        "ContrastAmount=0.65\nContrastEffect=1\n"
        "IntensityAmount=0.1\nIntensityEffect=2\n\n"
        "[ColorEffects:Inactive]\n"
        "ChangeSelectionColor=true\nColor=112,111,110\nColorAmount=0.025\n"
        "ColorEffect=2\nContrastAmount=0.1\nContrastEffect=2\n"
        "IntensityAmount=0\nIntensityEffect=0\n\n"
        "[General]\n"
        "ColorScheme=Voidashi\n"
        "Name=Voidashi\n"
        "shadeSortColumn=true\n"
    )
    return out


def merge_ini_keys(lines: list, keyed: dict) -> list:
    """Set specific keys in an INI file, leaving every other line untouched.

    For files where the keys we own sit beside keys another program writes, so
    replacing whole sections would throw away settings that are not ours. A key
    the file does not already carry is inserted under its section, and a section
    that does not exist is appended, because a fresh config must still come out
    complete rather than silently missing a font.
    """
    out, current = [], None
    seen = {section: set() for section in keyed}
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            current = stripped[1:-1]
        elif current in keyed and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            if key in keyed[current]:
                seen[current].add(key)
                line = f"{key}={keyed[current][key]}"
        out.append(line)

    for section, pairs in keyed.items():
        missing = [k for k in pairs if k not in seen[section]]
        if not missing:
            continue
        # Locate the header the same way the loop above recognised it, on the
        # stripped line. Matching the raw line instead meant a header written
        # as "[General] " was found when replacing a key and not found here,
        # so a second [General] was appended to a file that already had one.
        at = next((i for i, l in enumerate(out) if l.strip() == f"[{section}]"), None)
        if at is None:
            out += ["", f"[{section}]"] + [f"{k}={pairs[k]}" for k in missing]
        else:
            for key in reversed(missing):
                out.insert(at + 1, f"{key}={pairs[key]}")
    return out


def kcm_input_merged(current: str, p: dict) -> str:
    """The cursor theme and size, which live in kcminputrc rather than kdeglobals.

    KDE's gtkconfig daemon reads them from here and writes them into both GTK
    settings.ini files, so this is the only place the cursor has to be set for
    Qt and GTK to agree.
    """
    t = p["typography"]
    keyed = {"Mouse": {"cursorTheme": t["cursor_theme"],
                       "cursorSize": str(t["cursor_size"])}}
    return "\n".join(merge_ini_keys(current.splitlines(), keyed)).strip() + "\n"


def kde_globals_merged(current: str, scheme: str, p: dict) -> str:
    """Replace the colour sections of kdeglobals and set the font keys.

    KDE applications read their palette from kdeglobals itself, not from the
    .colors file, which systemsettings only uses as a source to copy from. But
    kdeglobals also holds settings that are none of our business (animation
    factors, recent documents, shortcuts), and KDE tools write to it too. So
    this replaces the sections we own and copies everything else through
    untouched.

    Fonts are the exception to that shape, because they sit in [General]
    alongside keys we must not touch, so they are set key by key instead of by
    replacing the section. They matter beyond Qt: KDE's gtkconfig daemon reads
    them here and writes them into both GTK settings.ini files, which is why
    those two files stopped being worth hand-editing. See docs/MAINTENANCE.md.
    """
    owned = lambda name: (
        name.startswith("Colors:") or name == "WM" or name.startswith("ColorEffects:")
    )
    # section -> key -> value, merged in rather than replacing the section.
    t = p["typography"]
    keyed = {
        "General": {
            "font": kde_font(p),
            "fixed": kde_font(p, mono=True),
            "menuFont": kde_font(p),
            "toolBarFont": kde_font(p),
            "smallestReadableFont": kde_font(p, size_key="small_size"),
        },
        "Icons": {"Theme": t["icon_theme"]},
    }

    kept, section, keep_current = [], None, True
    for line in current.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped[1:-1]
            keep_current = not owned(section)
        if keep_current:
            kept.append(line)
    kept = merge_ini_keys(kept, keyed)

    # Drop the scheme's own [General], which would collide with the one already
    # in kdeglobals; only its colour sections are wanted here.
    body, section, emit = [], None, False
    for line in scheme.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped[1:-1]
            emit = owned(section)
        if emit:
            body.append(line)

    # strip() at both ends, not rstrip(): on a machine with no kdeglobals yet,
    # merge_ini_keys starts the section it appends with a blank line, so the
    # file came out beginning with one. The condition that used to stand here,
    # "if l.strip() or kept", was true for every line whenever kept was
    # non-empty and so never dropped anything.
    text = "\n".join(kept).strip() + "\n\n"
    text += "\n".join(body).rstrip() + "\n"
    return text


